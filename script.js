/* ==========================================
   SHOW DESTINATION DETAILS
   ========================================== */

function showDetails(destination) {

    const data = destinationData[destination];

    if (!data) {
        return;
    }

    const detailsSection = document.getElementById("destination-details");
    const title = document.getElementById("det-title");
    const placesDiv = document.getElementById("det-places");
    const thingsDiv = document.getElementById("det-things");
    const nearDiv = document.getElementById("det-near");

    title.innerText = data.title;

    placesDiv.innerHTML = data.places
        .map(place => `<p>• ${place}</p>`)
        .join("");

    thingsDiv.innerHTML = data.things
        .map(thing => `<p>• ${thing}</p>`)
        .join("");

    nearDiv.innerHTML = data.near
        .map(place => `<p>• ${place}</p>`)
        .join("");

    detailsSection.style.display = "block";

    setTimeout(() => {
        detailsSection.scrollIntoView({
            behavior: "smooth",
            block: "start"
        });
    }, 50);
}


/* ==========================================
   CLOSE DESTINATION DETAILS
   ========================================== */

function closeDetails() {

    const detailsSection = document.getElementById("destination-details");

    detailsSection.style.display = "none";
}


/* ==========================================
   MOBILE HAMBURGER MENU
   ========================================== */

const hamburger = document.getElementById("hamburger");
const navLinks = document.querySelector(".nav-links");

if (hamburger) {

    hamburger.addEventListener("click", function () {

        navLinks.classList.toggle("active");

    });
}


/* ==========================================
   CLOSE MOBILE MENU AFTER CLICK
   ========================================== */

document.querySelectorAll(".nav-links a").forEach(function (link) {

    link.addEventListener("click", function () {

        navLinks.classList.remove("active");

    });

});